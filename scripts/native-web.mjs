import {readFile, writeFile, mkdir} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import {parse} from 'parse5'

// Vite owns bundling. This step only seals the offline document and embeds its bytes for NSH.
let html = await readFile('.local-build/native-web/index.html', 'utf8')
const hashes = []
function visit(node) {
  if (node.tagName === 'script') {
    if (node.attrs.some(attr => attr.name === 'src')) throw new Error('Native scripts must be inline')
    const text = node.childNodes.map(child => child.value ?? '').join('')
    hashes.push(`'sha256-${createHash('sha256').update(text).digest('base64')}'`)
  }
  if (node.attrs?.some(attr => ['src', 'href'].includes(attr.name) && /^(?:https?:|\/)/.test(attr.value))) {
    // Ordinary hyperlinks are safe; they cannot load resources under the CSP below.
    if (node.tagName !== 'a') throw new Error(`Native resource is not embedded: ${node.tagName}`)
  }
  for (const child of node.childNodes ?? []) visit(child)
}
visit(parse(html))
const policy = `default-src 'none'; script-src ${hashes.join(' ')}; style-src 'unsafe-inline'; img-src data: blob: https:; font-src data:; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`
html = html.replace('<head>', `<head><meta http-equiv="Content-Security-Policy" content="${policy}">`)
await mkdir('native/generated', {recursive: true})
await writeFile('native/generated/web.ts', `// Generated by bun run build:native-web. Do not edit.\nexport default ${JSON.stringify({html, baseUrl: 'https://inkmark.localhost/'})};\n`)
await writeFile('.local-build/native-web/index.html', html)
console.log(`Embedded offline document: ${Buffer.byteLength(html)} bytes; ${hashes.length} script hashes`)
