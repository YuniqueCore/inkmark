import {expect, open, test} from 'nsh/test'

test('native controls and real WebView: import, CRLF edit, preview review, close guard, export retry and image coordinates', async () => {
  const app = await open('./App.tsx')
  await app.setViewport(1440, 900)
  const stage = async (status: string) => {
    await app.waitUntil(() => app.texts().some(text => text.includes(`"status":"${status}"`) || text.includes('"status":"failed"')), {timeout: 30000})
    const result = JSON.parse(app.texts().find(text => text.includes('"status":'))!)
    expect(result.status).toBe(status)
    return result
  }
  const action = async (id: string) => { await app.press('id:workspace-menu'); await app.press(`id:action-${id}`) }
  await app.waitUntil(() => app.shows('id:welcome-new'), {timeout: 20000})
  await app.press('id:import-files')
  await stage('imported')
  await action('edit')
  await app.waitUntil(() => app.shows('id:text-entry'))
  expect(app.value('id:text-entry')).toBe('# Native review\n\nA **stable primitive** composes.')
  await app.keyboard.press('mod+enter')
  await app.waitUntil(() => !app.shows('id:text-entry'))
  await app.press('id:reading-split')
  await stage('selected')
  await app.press('id:selection-annotate')
  await app.type('id:annotation-comment', 'Native controls review')
  await app.window('main').pressClose()
  await app.waitUntil(() => app.texts().some(text => text.includes('请先提交或取消')))
  expect(app.value('id:annotation-comment')).toBe('Native controls review')
  await app.keyboard.press('mod+enter')
  await stage('annotated')
  await app.press('text:关闭提示')
  // A long localized name must leave every trailing action reachable at desktop widths.
  for (const width of [900, 1024, 1440]) {
    await app.setViewport(width, 900)
    await app.press('id:reading-preview')
    await app.press('id:reading-split')
    await app.press('id:export-review')
    await app.press('id:form-close')
  }
  // NSH 0.5.1 Windows traversal reaches text inputs only; other desktop hosts enter tabs.
  if (app.shows('id:journey-platform-macos') || app.shows('id:journey-platform-linux')) {
    await app.press('id:reading-source')
    let attempts = 0
    while (app.spanStyle('text:分栏').fontWeight !== 600) {
      expect(++attempts).toBeLessThan(25)
      await app.keyboard.press('tab')
      await app.keyboard.press('right')
    }
    await app.keyboard.press('end')
    await app.waitUntil(() => app.spanStyle('text:预览').fontWeight === 600)
    await app.keyboard.press('home')
    await app.waitUntil(() => app.spanStyle('text:源码').fontWeight === 600)
  }
  await app.press('id:reading-split')
  await app.screenshot('.local-build/native-evidence/workspace-desktop.png')
  // Keyboard commands must also work while a native control, rather than WebView, has focus.
  await app.press('id:reviews-toggle')
  await app.keyboard.press('mod+f')
  await app.waitUntil(() => app.shows('id:search-query'))
  await app.type('id:annotation-comment', 'Unsubmitted batch review')
  await app.keyboard.press('mod+q')
  expect(app.value('id:annotation-comment')).toBe('Unsubmitted batch review')
  await app.press('id:form-close')
  await app.press('id:discard-keep')
  expect(app.value('id:annotation-comment')).toBe('Unsubmitted batch review')
  await app.press('id:form-close')
  await app.press('id:discard-confirm')
  await app.keyboard.press('mod+s')
  await app.waitUntil(() => app.shows('id:export-save'))
  await app.press('text:W3C 批注')
  await app.press('id:export-save')
  await app.waitUntil(() => app.enabled('id:export-save'))
  await app.press('id:export-save')
  await app.waitUntil(() => app.texts().some(text => text.includes('Test disk unavailable')))
  await app.press('id:export-save')
  await app.waitUntil(() => app.texts().some(text => text.includes('文件已保存')))
  await app.press('id:form-close')
  await action('paste-image')
  await app.waitUntil(() => app.shows('id:image-coordinates') && app.enabled('id:image-coordinates'))
  await app.press('id:image-coordinates')
  await app.type('id:region-x', '-')
  await app.press('id:form-cancel')
  await app.waitUntil(() => !app.shows('id:region-x'))
  await app.press('id:image-coordinates')
  await app.type('id:annotation-comment', 'Review the red pixel')
  await app.keyboard.press('escape')
  await app.press('id:discard-keep')
  expect(app.value('id:annotation-comment')).toBe('Review the red pixel')
  await app.press('id:annotation-save')
  expect(await stage('passed')).toEqual({status: 'passed', documents: 2, annotations: [1, 1]})
  await app.press('text:关闭提示')
  await app.press('id:reviews-toggle')
  await app.press('text:筛选与选择 · 全部')
  await app.press('text:全部批注')
  await app.press('text:已解决')
  await app.keyboard.press('escape')
  await app.waitUntil(() => app.shows('id:reviews-clear-filter'))
  expect(app.texts()).toContain('没有符合筛选条件的批注。')
  await app.press('id:reviews-clear-filter')
  await app.waitUntil(() => app.texts().includes('Review the red pixel'))
  await app.press('id:documents-selecting')
  await app.press('id:documents-select-all')
  await app.waitUntil(() => app.texts().includes('已选 2 篇文档'))
  await app.setViewport(390, 844)
  await app.press('id:documents-toggle')
  expect(app.texts()).toContain('已选 2 篇文档')
  expect(app.shows('id:documents-export')).toBe(true)
  await app.press('text:返回阅读')
  await app.press('id:documents-toggle')
  expect(app.texts()).toContain('已选 2 篇文档')
  await app.screenshot('.local-build/native-evidence/documents-selection-compact.png')
  await app.press('text:返回阅读')
  await app.setViewport(1024, 900)
  expect(app.texts()).toContain('已选 2 篇文档')
  await app.press('id:documents-selecting')
  await app.waitUntil(() => !app.shows('id:documents-selection-count'))
  expect(app.shows('id:documents-export')).toBe(false)
  await app.press('id:documents-selecting')
  await app.waitUntil(() => !app.shows('id:documents-selection-count') && app.texts().includes('全选'))
  expect(app.shows('id:documents-export')).toBe(false)
  await app.press('id:documents-selecting')
  await app.screenshot('.local-build/native-evidence/workspace-medium.png')
  await app.setViewport(390, 844)
  await app.press('id:reviews-toggle')
  await app.waitUntil(() => app.texts().some(text => text.includes('Review the red pixel')))
  await app.press('text:返回阅读')
  expect(app.shows('id:workspace')).toBe(true)
  await app.screenshot('.local-build/native-evidence/workspace-compact.png')
}, 120000)
