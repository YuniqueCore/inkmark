test('image input boundaries and failed persistence preserve review data and a complete recovery backup', async ({page}) => {
  await page.goto('/')
  await expect(page.locator('#save-text')).toHaveText('已保存')
  const bytes = await picture(page)
  await test.step('Bad image data and executable formats cannot enter the workspace', async () => {
    await pastePicture(page, Buffer.from('<svg onload="alert(1)"></svg>'), 'hostile.svg', 'body', 'image/svg+xml')
    await expect(page.getByText(/仅支持 PNG/)).toBeVisible()
    await pastePicture(page, Buffer.from('not an image'))
    await expect(page.locator('#image-view')).toBeHidden()
    expect((await workspace(page)).docs).toHaveLength(0)
    await pastePicture(page, Buffer.alloc(12 * 1024 * 1024 + 1))
    await expect(page.getByText(/单张图片/)).toBeVisible()
  })
  await pastePicture(page, bytes)
  await expect(page.locator('.a9s-annotationlayer')).toBeVisible()
  await test.step('Native input paste is not intercepted; Escape cancels an unsubmitted region atomically', async () => {
    await page.locator('[data-image-action="coordinates"]').click()
    await pastePicture(page, bytes, 'ignored.png', '[data-image-form] textarea')
    await page.locator('[data-image-form] textarea').fill('取消这个未提交区域')
    await page.keyboard.press('Escape')
    await expect(page.locator('.image-composer')).toBeHidden()
    await expect(page.locator('#sidebar .ann-card')).toHaveCount(0)
    await expect.poll(async () => (await workspace(page)).docs.length).toBe(1)
  })
  await test.step('A failed IndexedDB transaction is visible and a backup includes unsaved committed annotations', async () => {
    await page.evaluate(() => {
      IDBObjectStore.prototype.put = function () { throw new DOMException('Quota exceeded', 'QuotaExceededError') }
    })
    await drawRegion(page, [50, 200], [390, 370])
    await page.locator('[data-image-form] textarea').fill('存储失败时需要找回的意见')
    await page.locator('[data-image-save]').click()
    await expect(page.locator('#save-error')).toBeVisible()
    const downloadPromise = page.waitForEvent('download')
    await page.locator('#btn-recovery-backup').click()
    const backup = await readFile((await (await downloadPromise).path())!)
    const parsed = JSON.parse(backup.toString())
    expect(parsed.docs[0].annotations[0].comment).toBe('存储失败时需要找回的意见')
    expect(Buffer.from(parsed.docs[0].image.dataUrl.split(',')[1], 'base64')).toEqual(bytes)
    await page.reload()
    await expect(page.locator('.a9s-annotationlayer')).toBeVisible()
    await expect(page.locator('#sidebar .ann-card')).toHaveCount(0)
    await page.locator('#file-input').setInputFiles({name: 'recovered.json', mimeType: 'application/json', buffer: backup})
    await expect(page.locator('#sidebar .ann-card')).toContainText('存储失败时需要找回的意见')
    await expect(page.locator('#save-text')).toHaveText('已保存')
  })
})

test('two tabs never overwrite divergent work; complete recovery preserves the trash and restores atomically', async ({page, context}) => {
  await page.goto('/')
  await createDoc(page, 'First tab original document.', true)
  await expect(page.locator('#save-text')).toHaveText('已保存')
  const other = await context.newPage()
  await other.goto('/')
  await expect(other.locator('#editor')).toContainText('First tab original document.')
  await page.locator('#btn-edit').click()
  await page.locator('#edit-source').fill('First tab updated document.')
  await page.getByRole('button', {name: '完成并重锚批注'}).click()
  await expect(page.locator('#save-text')).toHaveText('已保存')
  await createDoc(other, 'Second tab private draft to recover.')
  await expect(other.locator('#save-text')).toContainText('另一标签页')
  await other.locator('#btn-more').click()
  await other.getByRole('menuitem', {name: '移除当前文档'}).click()
  await other.getByRole('alertdialog').getByRole('button', {name: '移除', exact: true}).click()
  await expect(other.locator('#save-error')).toBeVisible()
  const downloadPromise = other.waitForEvent('download')
  await other.locator('#btn-recovery-backup').click()
  const backup = await readFile((await (await downloadPromise).path())!)
  const data = JSON.parse(backup.toString())
  expect(data.trash[0].doc.text).toBe('Second tab private draft to recover.')
  expect((await workspace(page)).docs[0].text).toBe('First tab updated document.')
  await other.reload()
  await expect(other.locator('#editor')).toContainText('First tab updated document.')
  await other.evaluate(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args: Parameters<IDBObjectStore['put']>) {
      const result = put.apply(this, args)
      const until = performance.now() + 350
      const keepAlive = () => { if (performance.now() < until) this.get('workspace').onsuccess = keepAlive }
      keepAlive()
      return result
    }
  })
  await other.locator('#workspace-input').setInputFiles({name: 'recovery.json', mimeType: 'application/json', buffer: backup})
  await other.getByRole('alertdialog').getByRole('button', {name: '恢复工作区', exact: true}).click()
  await expect.poll(() => other.evaluate(() => document.body.inert)).toBe(true)
  await expect(other.getByText('完整工作区已恢复')).toBeVisible()
  await expect.poll(() => other.evaluate(() => document.body.inert)).toBe(false)
  await other.locator('#btn-trash').click()
  await other.locator('[data-op="restore"]').click()
  await other.getByRole('dialog').getByRole('button', {name: '关闭', exact: true}).click()
  await expect(other.locator('#save-text')).toHaveText('已保存')
  await other.reload()
  expect((await workspace(other)).docs.some((d: {text?: string}) => d.text === 'Second tab private draft to recover.')).toBe(true)
  await other.close()
})

test('fractional zoom moves preserve size and out-of-bounds moves cannot silently crop a saved region', async ({page}) => {
  await page.setViewportSize({width: 1440, height: 1000})
  await page.goto('/')
  await expect(page.locator('#save-text')).toHaveText('已保存')
  await pastePicture(page, await picture(page))
  await expect(page.locator('[data-image-action="coordinates"]')).toBeEnabled()
  await page.locator('[data-image-action="coordinates"]').click()
  await page.locator('[data-coordinate="x"]').fill('80')
  await page.locator('[data-coordinate="y"]').fill('80')
  await saveRegion(page, '移动不能改变面积')
  await page.locator('[data-image-action="original"]').click()
  await page.locator('[data-image-action="in"]').click()
  await expect(page.locator('[data-image-zoom]')).toHaveText('125%')
  await expect(page.locator('.a9s-rotation-handle-group')).toBeHidden()
  let x = 80
  for (let move = 0; move < 4; move++) {
    const image = (await page.locator('#image-view img').boundingBox())!
    const center = {x: image.x + (x + 50) * 1.25, y: image.y + 130 * 1.25}
    await page.mouse.move(center.x, center.y); await page.mouse.down()
    await page.mouse.move(center.x + 2, center.y, {steps: 3}); await page.mouse.up()
    x += 2
    await expect.poll(async () => (await workspace(page)).docs[0].annotations[0].selector).toEqual({type: 'rectangle', x, y: 80, width: 100, height: 100})
  }
  await page.locator('[data-image-action="fit"]').click()
  await page.locator('#sidebar [data-op="edit"]').click()
  await page.locator('[data-coordinate="x"]').fill('9999')
  await page.locator('[data-image-form] textarea').click()
  await expect(page.locator('[data-coordinate="x"]')).toHaveValue('9999')
  await expect(page.locator('[data-image-save]')).toBeDisabled()
  await page.locator('[data-image-cancel]').click()
  await page.locator('#sidebar button[data-op="focus"]').click()
  const image = (await page.locator('#image-view img').boundingBox())!
  const scale = image.width / 900
  await page.mouse.move(image.x + (x + 50) * scale, image.y + 130 * scale)
  await page.mouse.down(); await page.mouse.move(image.x - 10, image.y + 130 * scale, {steps: 10}); await page.mouse.up()
  await expect(page.getByText('区域不能超出图片，已恢复之前的位置')).toBeVisible()
  expect((await workspace(page)).docs[0].annotations[0].selector).toEqual({type: 'rectangle', x, y: 80, width: 100, height: 100})
  await page.locator('[data-image-action="original"]').click()
  await page.locator('.image-viewport').evaluate((el) => { el.scrollLeft = el.scrollWidth; el.scrollTop = el.scrollHeight })
  await page.locator('#sidebar button[data-op="focus"]').click()
  await expect.poll(() => page.locator('.image-viewport').evaluate((el) => el.scrollLeft)).toBe(0)
  const wideImage = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 16384; canvas.height = 100
    return canvas.toDataURL().split(',')[1]!
  })
  await page.locator('#file-input').setInputFiles({name: 'wide.png', mimeType: 'image/png', buffer: Buffer.from(wideImage, 'base64')})
  await page.setViewportSize({width: 160, height: 844})
  await expect(page.locator('[data-image-action="coordinates"]')).toBeEnabled()
  const before = (await page.locator('#image-view img').boundingBox())!.width
  await page.locator('[data-image-action="out"]').click()
  expect((await page.locator('#image-view img').boundingBox())!.width).toBeLessThan(before)
})

test.describe('touch image browsing', () => {
  test.use({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true})
  test('touch pan remains available alongside a draft and switching images resets the tool', async ({page, context}) => {
    await page.goto('/')
    await expect(page.locator('#save-text')).toHaveText('已保存')
    const bytes = await picture(page)
    await pastePicture(page, bytes)
    await expect(page.locator('[data-image-action="coordinates"]')).toBeEnabled()
    await page.locator('[data-image-action="original"]').tap()
    await page.locator('[data-image-action="pan"]').tap()
    await expect(page.locator('[data-image-action][aria-pressed="true"]')).toHaveCount(1)
    const viewport = (await page.locator('.image-viewport').boundingBox())!
    const cdp = await context.newCDPSession(page)
    const x = viewport.x + viewport.width / 2; const y = viewport.y + viewport.height * 0.75
    await cdp.send('Input.dispatchTouchEvent', {type: 'touchStart', touchPoints: [{x, y}]})
    for (let i = 1; i <= 6; i++) await cdp.send('Input.dispatchTouchEvent', {type: 'touchMove', touchPoints: [{x, y: y - i * 20}]})
    await cdp.send('Input.dispatchTouchEvent', {type: 'touchEnd', touchPoints: []})
    await expect.poll(() => page.locator('.image-viewport').evaluate((el) => el.scrollTop)).toBeGreaterThan(30)
    await page.locator('[data-image-action="coordinates"]').tap()
    await expect(page.locator('#image-view')).toHaveAttribute('data-tool', 'select')
    await page.locator('[data-image-action="pan"]').tap()
    await page.locator('[data-image-action="select"]').tap()
    await expect(page.locator('.a9s-annotation.selected')).toBeVisible()
    await page.locator('[data-image-cancel]').tap()
    await page.locator('[data-image-action="pan"]').tap()
    await pastePicture(page, bytes, 'second.png')
    await expect(page.locator('[data-image-action="coordinates"]')).toBeEnabled()
    await expect(page.locator('#image-view')).toHaveAttribute('data-tool', 'draw')
    await expect(page.locator('[data-image-action][aria-pressed="true"]')).toHaveCount(1)
  })
})
